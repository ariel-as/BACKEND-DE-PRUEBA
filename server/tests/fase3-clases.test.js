import test from 'node:test';
import assert from 'node:assert/strict';
import { tokens, api, cedula, ensureShift } from './helpers.js';
import { prisma } from '../config/prisma.js';
import { localToday, weekday, normalizeDay } from '../utils/dates.js';

test('fase 3 §3: clases, cupo por horario, reservas y reporte de asistencia', async () => {
  const tk = await tokens(), adm = api(tk.ADM), rec = api(tk.REC), cli = api(tk.CLI);
  await ensureShift(tk.REC);
  const horarios = await prisma.horario.findMany();
  const horario = horarios.find((h) => normalizeDay(h.dia) === normalizeDay(weekday(localToday())));
  assert.ok(horario, 'no hay horario para hoy');
  const nombre = `Clase Fase3 ${Date.now()}`;
  const crear = (cnt) => ({ nombre: cnt, servicioId: 'BOX', empleadoId: '1700000019', descripcion: 'Clase de prueba fase 3', lugar: 'Planta baja', cupoMax: 1, horarios: [horario.id] });
  const clase = await adm.post('/admin/clases', crear(nombre));
  assert.equal(clase.status, 201, JSON.stringify(clase.body));
  assert.equal(clase.body.entrenadorId, '1700000019');
  assert.equal(clase.body.horarios[0].cupoMax, 1);
  assert.equal(clase.body.horarios[0].cupoDisponible, 1);
  assert.equal((await adm.post('/admin/clases', crear(`${nombre}-dup`))).status, 201);
  const repetido = await adm.post('/admin/clases', { ...crear(`${nombre}-rep`), horarios: [horario.id, horario.id] });
  assert.equal(repetido.status, 400);
  const filtradas = await rec.get(`/admin/clases?estado=A&entrenadorId=1700000019&dia=${encodeURIComponent(horario.dia)}`);
  assert.equal(filtradas.status, 200, JSON.stringify(filtradas.body));
  assert.ok(filtradas.body.data.some((c) => c.id === clase.body.id));
  assert.equal((await rec.get('/admin/clases?otro=1')).status, 400);
  assert.equal((await adm.put(`/admin/clases/${clase.body.id}`, { lugar: 'Segundo piso' })).status, 200);
  const catalogo = (await cli.get('/clases')).body.find((c) => c.id === clase.body.id);
  assert.equal(catalogo.horarios[0].cupoDisponible, 1);
  const inscribir = async (clienteId) => {
    const r = await rec.post('/admin/inscripciones', { clienteId, membresiaId: 'MI1', fechaInicio: localToday(), pagos: [{ metodoPago: 'EF', monto: 35 }] });
    assert.equal(r.status, 201, JSON.stringify(r.body));
    return r.body.id;
  };
  const acompanante = cedula(`173${String(Date.now()).slice(-6)}`);
  assert.equal((await rec.post('/admin/clientes', { cedula: acompanante, nombre: 'Reserva', apellido: 'Fase Tres', nivelId: 'PRI' })).status, 201);
  const ins1 = await inscribir('1712345675'), ins2 = await inscribir(acompanante);
  const reserva = await rec.post(`/admin/inscripciones/${ins1}/clases`, { claseId: clase.body.id, horarioId: horario.id, cupoMax: 1 });
  assert.equal(reserva.status, 201, JSON.stringify(reserva.body));
  assert.equal(reserva.body.cupoDisponible, 0);
  const llena = await rec.post(`/admin/inscripciones/${ins2}/clases`, { claseId: clase.body.id, horarioId: horario.id, cupoMax: 1 });
  assert.equal(llena.status, 409, JSON.stringify(llena.body));
  const reporte = await rec.get(`/admin/reportes/asistencia?claseId=${clase.body.id}&entrenadorId=1700000019`);
  assert.equal(reporte.status, 200, JSON.stringify(reporte.body));
  assert.ok(reporte.body.resumen.porClase.find((c) => c.claseId === clase.body.id && c.reservas >= 1));
  assert.ok(reporte.body.resumen.porEntrenador.find((e) => e.entrenadorId === '1700000019' && e.reservas >= 1));
  assert.ok(reporte.body.detalle.find((d) => d.claseId === clase.body.id && d.clienteId === '1712345675'));
  assert.equal((await adm.delete(`/admin/clases/${clase.body.id}`)).status, 200);
  assert.equal((await adm.get(`/admin/clases/${clase.body.id}`)).body.estado, 'I');
  assert.ok((await adm.get('/admin/clases?estado=I')).body.data.some((c) => c.id === clase.body.id));
  await prisma.$disconnect();
});
